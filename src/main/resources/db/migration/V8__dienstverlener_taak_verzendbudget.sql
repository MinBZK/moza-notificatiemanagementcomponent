-- V8: dienstverlener, takentabel en verzendbudget uit ADR 0024. Tot de tokenvalidatie per
-- dienstverlener er is, is er één geconfigureerde dienstverlener; notificatie en event dragen zijn
-- dv_id, zodat claim, sleutel en feed er nu al op werken.

CREATE TABLE dienstverlener (
    id uuid PRIMARY KEY,
    oin varchar(20) NOT NULL UNIQUE,
    naam varchar(200) NOT NULL
);

-- Vaste id, gelijk aan de default van nmc.dienstverlener.id. Het OIN is een placeholder tot de
-- onboarding het echte levert.
INSERT INTO dienstverlener (id, oin, naam)
